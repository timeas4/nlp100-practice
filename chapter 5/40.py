
#Zero-Shot推論
import os
from google import genai

client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])

question = """9世紀に活躍した人物に関係するできごとについて述べた次のア～ウを年代の古い順に正しく並べよ。

ア　藤原時平は，策謀を用いて菅原道真を政界から追放した。
イ　嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。
ウ　藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。"""

response = client.models.generate_content(
    model="gemini-2.5-flash",
    contents=question,
)
print(response.text)

'''
年代の古い順に並べると以下の通りです。

*   **イ　嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。**
    *   この出来事は、薬子の変（810年）の直後に蔵人所が設置された際のことです。藤原冬嗣は初代蔵人頭の一人として任命されました。
    *   **810年**

*   **ウ　藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。**
    *   承和の変は**842年**に起きました。この変で藤原良房は政敵を排除し、藤原北家の政治的地位を確立しました。

*   **ア　藤原時平は，策謀を用いて菅原道真を政界から追放した。**
    *   これは昌泰の変（菅原道真の左遷）として知られ、**901年**に起こりました。

したがって、年代の古い順に並べると、
**イ (810年) → ウ (842年) → ア (901年)**
となります。

**正しい並び順：イ、ウ、ア**
'''